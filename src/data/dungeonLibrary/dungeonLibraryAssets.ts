export function getDungeonMonsterDriveId(enemyId?: number | string | null): string | undefined {
  if (enemyId == null || enemyId === "") return undefined;
  const id = typeof enemyId === "number" ? enemyId : Number(String(enemyId).trim());
  if (!Number.isInteger(id)) return undefined;
  if (!Object.prototype.hasOwnProperty.call(DUNGEON_MONSTER_DRIVE_IDS, id)) return undefined;
  return DUNGEON_MONSTER_DRIVE_IDS[id as DungeonMonsterEnemyId];
}

