// Shared, browser-safe vocabulary. Never accept arbitrary upstream error text.
export const YOUTUBE_ERROR_CODES = [
  "YOUTUBE_SOURCES_INVALID", "YOUTUBE_NOT_CONFIGURED", "YOUTUBE_API_REJECTED",
  "YOUTUBE_CHANNEL_MISSING", "YOUTUBE_PLAYLIST_MISSING", "YOUTUBE_UPLOADS_MISSING",
  "YOUTUBE_TIMEOUT", "YOUTUBE_UNREACHABLE", "YOUTUBE_RESPONSE_INVALID",
  "YOUTUBE_CHANNEL_METADATA_MISSING", "YOUTUBE_SNAPSHOT_INCOMPLETE",
  "YOUTUBE_CACHE_MISSING", "YOUTUBE_PAGINATION_CYCLE", "YOUTUBE_SNAPSHOT_READ_FAILED",
  "YOUTUBE_CACHE_READ_FAILED", "YOUTUBE_SNAPSHOT_WRITE_FAILED", "YOUTUBE_LOCK_FAILED",
  "YOUTUBE_LOCK_EXPIRED", "YOUTUBE_SYNC_BUSY", "YOUTUBE_REFRESH_FAILED",
  "YOUTUBE_SNAPSHOT_MISSING", "YOUTUBE_SNAPSHOT_UNAVAILABLE", "YOUTUBE_ACCESS_DENIED",
  "ADMIN_CHECK_UNAVAILABLE",
] as const;
export type YouTubeErrorCode = typeof YOUTUBE_ERROR_CODES[number];
export function isYouTubeErrorCode(value: unknown): value is YouTubeErrorCode {
  return typeof value === "string" && (YOUTUBE_ERROR_CODES as readonly string[]).includes(value);
}
